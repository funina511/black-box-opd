#!/usr/bin/env python3
"""Build a tiny synthetic dataset for CPU checks and GPU smoke runs.

The teacher text produced here is **synthetic** (derived from the prompt and the
ground truth) and is only meant to exercise the pipeline plumbing: it lets you
run the data contract checks, the pipeline ``--dry-run``, and a short GPU smoke
test without standing up a teacher endpoint.

Never use this output for a real experiment: the GAD reward would be trained
against a fake teacher. Every artifact is written next to a
``SYNTHETIC_DATA_WARNING.txt`` and the manifest records ``synthetic: true``.

Example::

    python LMOps/sample/make_smoke_data.py \
        --prompt-parquet /abs/path/data/dapo_all_v1/train.parquet \
        --out-dir /abs/path/data/smoke_v1 --prompts 64 --dev-prompts 8
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import pyarrow as pa
import pyarrow.parquet as pq

sys.path.insert(0, str(Path(__file__).resolve().parent))

from teacher_index import GAD_INDEX_SCHEMA_VERSION, header_record  # noqa: E402
from task_template import (  # noqa: E402
    build_teacher_fingerprint_payload,
    canonicalize_raw_prompt,
    extract_question_text,
    hash_raw_prompt,
    hash_teacher_fingerprint,
    normalize_raw_prompt,
)

WARNING = (
    "SYNTHETIC DATA - generated by make_smoke_data.py.\n"
    "The teacher responses in this directory are fabricated from the prompt and the\n"
    "ground truth. They are only for plumbing/smoke tests and MUST NOT be used for\n"
    "training runs that are reported as experiments.\n"
)


def synth_answer(problem: str, ground_truth: str, index: int) -> str:
    snippet = problem.strip().splitlines()[0][:120] if problem.strip() else "the problem"
    return (
        f"[SYNTHETIC TEACHER {index}] Working through: {snippet}\n"
        f"Step 1: identify what is asked.\n"
        f"Step 2: apply the relevant method.\n"
        f"Step 3: simplify.\n"
        f"Answer: {ground_truth}"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--prompt-parquet", required=True, help="Prompt parquet (train split is enough).")
    parser.add_argument("--dev-parquet", default=None, help="Optional separate prompts for the dev split.")
    parser.add_argument("--out-dir", required=True)
    parser.add_argument("--prompts", type=int, default=64)
    parser.add_argument("--dev-prompts", type=int, default=8)
    parser.add_argument("--answers-per-prompt", type=int, default=2)
    args = parser.parse_args()

    from build_gad_data import GAD_OUTPUT_SCHEMA

    out_dir = Path(args.out_dir).expanduser().resolve()
    out_dir.mkdir(parents=True, exist_ok=True)

    table = pq.read_table(Path(args.prompt_parquet).expanduser())
    columns = set(table.column_names)
    key = "prompt" if "prompt" in columns else "content"
    rows = table.to_pylist()

    train_rows = rows[: args.prompts]
    if args.dev_parquet:
        dev_table = pq.read_table(Path(args.dev_parquet).expanduser())
        dev_rows = dev_table.to_pylist()[: args.dev_prompts]
    else:
        dev_rows = rows[args.prompts: args.prompts + args.dev_prompts]

    fingerprint = build_teacher_fingerprint_payload(
        provider="synthetic",
        model="synthetic-teacher",
        base_url=None,
        temperature=0.0,
        top_p=1.0,
        max_output_tokens=2048,
        num_samples=args.answers_per_prompt,
        seed=0,
    )
    digest = hash_teacher_fingerprint(fingerprint)

    index_lines = [
        json.dumps(
            header_record(
                fingerprint=fingerprint,
                created_by="make_smoke_data.py",
                notes={"synthetic": True, "enable_thinking": False},
            ),
            ensure_ascii=False,
        )
    ]
    for position, row in enumerate(train_rows + dev_rows):
        prompt = normalize_raw_prompt(row[key])
        ground_truth = str(row["reward_model"]["ground_truth"])
        answers = [
            synth_answer(extract_question_text(prompt), ground_truth, position * 10 + i)
            for i in range(args.answers_per_prompt)
        ]
        index_lines.append(
            json.dumps(
                {
                    "schema_version": GAD_INDEX_SCHEMA_VERSION,
                    "uid": str(row["extra_info"]["index"]),
                    "raw_prompt_hash": hash_raw_prompt(prompt),
                    "teacher_answers": answers,
                    "teacher_fingerprint": fingerprint,
                    "teacher_fingerprint_digest": digest,
                    "sampling": {"finish_reasons": ["stop"] * len(answers), "truncated": [False] * len(answers)},
                    "source": "synthetic",
                },
                ensure_ascii=False,
            )
        )
    index_path = out_dir / "teacher_index.jsonl"
    index_path.write_text("\n".join(index_lines) + "\n", encoding="utf-8")

    def build(rows_in, out_name, *, source_note: str):
        entries = []
        for position, row in enumerate(rows_in):
            prompt = normalize_raw_prompt(row[key])
            ground_truth = str(row["reward_model"]["ground_truth"])
            entries.append(
                {
                    "content": [{"role": m["role"], "content": m["content"]} for m in prompt],
                    "teacher_response": synth_answer(extract_question_text(prompt), ground_truth, position * 10),
                    "data_source": row.get("data_source", "math_dapo"),
                    "ability": row.get("ability", "MATH"),
                    "reward_model": {
                        "ground_truth": ground_truth,
                        "style": row["reward_model"].get("style", "rule-lighteval/MATH_v2"),
                    },
                    "extra_info": {"index": str(row["extra_info"]["index"])},
                }
            )
        pq.write_table(pa.Table.from_pylist(entries, schema=GAD_OUTPUT_SCHEMA), out_dir / out_name)
        return len(entries)

    train_n = build(train_rows, "train.parquet", source_note="train")
    dev_n = build(dev_rows, "dev.parquet", source_note="dev")

    (out_dir / "SYNTHETIC_DATA_WARNING.txt").write_text(WARNING, encoding="utf-8")
    (out_dir / "manifest.json").write_text(
        json.dumps(
            {
                "synthetic": True,
                "warning": WARNING,
                "prompt_parquet": str(Path(args.prompt_parquet).expanduser().resolve()),
                "prompts": train_n,
                "dev_prompts": dev_n,
                "answers_per_prompt": args.answers_per_prompt,
                "teacher_fingerprint_digest": digest,
                "index": str(index_path),
                "train_parquet": str(out_dir / "train.parquet"),
                "dev_parquet": str(out_dir / "dev.parquet"),
                "first_prompt_canonical": canonicalize_raw_prompt(normalize_raw_prompt(train_rows[0][key]))[:200]
                if train_rows
                else None,
            },
            ensure_ascii=False,
            indent=2,
        ),
        encoding="utf-8",
    )
    print(f"[make_smoke_data] {train_n} train / {dev_n} dev prompts -> {out_dir}")
    print(f"[make_smoke_data] synthetic fingerprint digest: {digest}")
    print("[make_smoke_data] WARNING: synthetic teacher text, plumbing tests only")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
